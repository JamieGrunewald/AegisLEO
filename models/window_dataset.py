"""
AegisLEO — Sliding Window Dataset Builder
==========================================

Created by: Jamie Grunewald
Date: 2026-03-26
Version: v0.1.0

Purpose
-------
Loads a telemetry CSV and converts it into overlapping sliding windows
suitable for sequence autoencoder training. Each window is a (window_size × features)
array representing a short temporal slice of nominal telemetry behavior.

The autoencoder is trained to reconstruct these windows. At runtime,
high reconstruction error on a new window signals anomalous behavior.

Feature columns must match Telemetry.to_feature_dict() exactly.
Do not reorder — changing the column list requires retraining from scratch.

Used by
-------
- models/train_seq_autoencoder.py   (training)
- models/runtime_detector.py        (future: live inference path)
"""

import numpy as np
import pandas as pd


FEATURE_COLUMNS = [
    "seq",
    "temperature_c",
    "battery_pct",
    "latitude",
    "longitude",
    "altitude_km",
    "bus_v",
    "bus_i",
    "mode_nominal",
    "mode_sunpoint",
    "mode_tx_window",
]


def build_windows(csv_path: str, window_size: int = 16) -> np.ndarray:
    """
    Load telemetry CSV and build overlapping sliding windows.

    Parameters
    ----------
    csv_path : str
        Path to the telemetry CSV generated by generate_normal_dataset.py.
    window_size : int
        Number of consecutive time steps per window. Must be smaller than
        the number of rows in the CSV. Default: 16.

    Returns
    -------
    np.ndarray
        Shape (N, window_size, len(FEATURE_COLUMNS)), dtype float32.
        N = len(df) - window_size overlapping windows.
    """
    df = pd.read_csv(csv_path)
    X = df[FEATURE_COLUMNS].values.astype(np.float32)

    windows = []
    for i in range(len(X) - window_size):
        windows.append(X[i : i + window_size])

    return np.array(windows)
